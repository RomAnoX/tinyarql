// Generates ../../src/frontend/icons.js from lucide-static (ISC). Run: npm run icons
// Add a name here, run the script, then use icon('name') in the frontend or <i data-icon="name"></i> in the HTML.
import { readFileSync, writeFileSync } from 'node:fs';

const NAMES = [
  'database', 'table-2', 'eye', 'pencil', 'trash-2', 'plus', 'settings', 'play', 'chevron-left', 'chevron-right',
  'copy', 'check', 'x', 'braces', 'circle-alert', 'folder-open', 'sun', 'moon', 'monitor', 'file-text', 'list-tree',
  'hard-drive', 'unplug', 'plug-zap', 'loader-circle', 'square', 'save', 'file-code', 'download', 'search',
];

const inner = (name) => {
  const svg = readFileSync(`node_modules/lucide-static/icons/${name}.svg`, 'utf8');
  return svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').replace(/> </g, '><').trim();
};
const version = JSON.parse(readFileSync('node_modules/lucide-static/package.json', 'utf8')).version;

writeFileSync('../../src/frontend/icons.js', `// Generated by tools/editor/icons.mjs from lucide-static ${version} (ISC License, https://lucide.dev). Do not edit.
const ICONS = {
${NAMES.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(inner(n))},`).join('\n')}
};

// Inline SVG string. Decorative by default: icon-only buttons must carry their own aria-label.
function icon(name, size = 16) {
  if (!ICONS[name]) throw new Error('unknown icon: ' + name);
  return \`<svg class="i" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${ICONS[name]}</svg>\`;
}

// Static markup writes <i data-icon="play"></i> (optional data-size); this swaps them for the SVG.
function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => { el.outerHTML = icon(el.dataset.icon, +el.dataset.size || 16); });
}
`);
console.log(`wrote ${NAMES.length} icons`);
